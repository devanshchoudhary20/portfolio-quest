import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { PNG } from 'pngjs';
import { BG_IDS, SPECIES, TRAINER_SPRITES } from '../src/game/battle/data';

// Usage: tsx scripts/make-battle-placeholders.ts [outDir]; writes simple stand-in art, and only for files that do not exist yet, so the designer's art always wins
const ROOT = resolve(import.meta.dirname, '..');
const out = resolve(process.argv[2] ?? resolve(ROOT, 'public/assets/battle'));

type Rgb = [number, number, number];
const COLORS: Record<string, Rgb> = {
  water: [60, 198, 232],
  grass: [92, 184, 90],
  fire: [232, 121, 58],
  bug: [200, 73, 63],
  ghost: [140, 120, 200],
};
const INK: Rgb = [27, 31, 46];
const BGS: Record<string, { sky: Rgb; ground: Rgb }> = {
  grass: { sky: [168, 220, 244], ground: [92, 168, 74] },
  jungle: { sky: [120, 176, 120], ground: [52, 120, 60] },
  city: { sky: [196, 205, 224], ground: [150, 156, 172] },
  gym: { sky: [214, 200, 170], ground: [230, 220, 185] },
  elite: { sky: [40, 40, 70], ground: [70, 66, 96] },
};

const canvas = (w: number, h: number) => new PNG({ width: w, height: h });
const put = (png: PNG, x: number, y: number, [r, g, b]: Rgb) => {
  if (x < 0 || y < 0 || x >= png.width || y >= png.height) return;
  png.data.set([r, g, b, 255], (y * png.width + x) * 4);
};

// a round blob with an ink outline; the back view is a little bigger and darker, the way a back sprite reads
function blob(color: Rgb, back: boolean): PNG {
  const png = canvas(64, 64);
  const rx = back ? 26 : 20;
  const ry = back ? 24 : 20;
  const cy = back ? 40 : 38;
  for (let y = 0; y < 64; y++) {
    for (let x = 0; x < 64; x++) {
      const d = ((x - 32) / rx) ** 2 + ((y - cy) / ry) ** 2;
      if (d <= 1) put(png, x, y, d > 0.8 ? INK : back ? (color.map((c) => Math.round(c * 0.85)) as Rgb) : color);
    }
  }
  if (!back) for (const ex of [26, 38]) for (let y = 32; y < 36; y++) for (let x = ex; x < ex + 3; x++) put(png, x, y, INK);
  return png;
}

function person(color: Rgb): PNG {
  const png = canvas(64, 64);
  for (let y = 8; y < 60; y++) {
    for (let x = 22; x < 42; x++) {
      const head = y < 24;
      if (head && (x < 26 || x > 37)) continue;
      put(png, x, y, y < 12 || x === 22 || x === 41 ? INK : head ? [226, 180, 140] : color);
    }
  }
  return png;
}

function background(sky: Rgb, ground: Rgb): PNG {
  const png = canvas(320, 180);
  for (let y = 0; y < 180; y++) for (let x = 0; x < 320; x++) put(png, x, y, y < 60 ? sky : ground);
  return png;
}

const files = new Map<string, () => PNG>();
for (const species of SPECIES) {
  const color = COLORS[species.type] ?? COLORS.bug!;
  files.set(`creatures/${species.id}-front.png`, () => blob(color, false));
  files.set(`creatures/${species.id}-back.png`, () => blob(color, true));
}
TRAINER_SPRITES.forEach((id, i) => files.set(`trainers/${id}.png`, () => person(Object.values(COLORS)[i % 5]!)));
for (const id of BG_IDS) files.set(`bg/${id}.png`, () => background(BGS[id]!.sky, BGS[id]!.ground));

let written = 0;
for (const [name, make] of files) {
  const path = resolve(out, name);
  if (existsSync(path)) continue;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, PNG.sync.write(make()));
  written++;
}

const license = resolve(out, 'LICENSE.txt');
if (!existsSync(license)) {
  mkdirSync(out, { recursive: true });
  writeFileSync(license, 'Placeholder battle art generated by scripts/make-battle-placeholders.ts for Portfolio Quest.\nReleased under CC0 1.0 Universal (https://creativecommons.org/publicdomain/zero/1.0/).\n');
  written++;
}
console.log(`make-battle-placeholders: wrote ${written} of ${files.size + 1} files, ${files.size + 1 - written} already existed`);
